// Append U+FE0F (variation selector-16) so text-default glyphs render as emoji.
const NOTE_ICON_EMOJIS: string[] = NOTE_ICON_CODE_POINTS.map(
  (cp) => String.fromCodePoint(cp) + "\uFE0F"
);

export function hashString(str: string): number {
  let hash = 5381;
  for (let i = 0; i < str.length; i++) {
    hash = (Math.imul(hash, 33) ^ str.charCodeAt(i)) >>> 0;
  }
  return hash;
}

// Deterministically assign each note a unique emoji icon derived from its id.
export function assignNoteIcons<T extends { id: string }>(
  notes: T[]
): (T & { icon: string })[] {
  const used = new Set<string>();
  const sorted = [...notes].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const byId = new Map<string, string>();

  for (const note of sorted) {
    let index = hashString(note.id) % NOTE_ICON_EMOJIS.length;
    while (used.has(NOTE_ICON_EMOJIS[index])) {
      index = (index + 1) % NOTE_ICON_EMOJIS.length;
    }
    const emoji = NOTE_ICON_EMOJIS[index];
    used.add(emoji);
    byId.set(note.id, emoji);
  }

  return notes.map((note) => ({ ...note, icon: byId.get(note.id)! }));
}
